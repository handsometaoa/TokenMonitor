export type MessageKey = keyof typeof zh;

const messages: Record<Language, Record<MessageKey, string>> = { 'zh-CN': zh, en };

export function translate(language: Language, key: MessageKey, vars?: Record<string, string | number>): string {
  let value = messages[language]?.[key] ?? messages['zh-CN'][key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export type Translator = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function createTranslator(language: Language): Translator {
  return (key, vars) => translate(language, key, vars);
}
